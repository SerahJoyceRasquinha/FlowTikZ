import type { Diagram } from '../model/types';
import { diagramBounds } from '../model/diagram';
import { ColorRegistry } from './colors';
import { LibraryRegistry, baseStyleDefinitions } from './styles';
import { emitNode } from './nodes';
import { emitEdge } from './edges';
import { makeUnitContext, fmt } from './units';
import { validateDiagram, ValidationIssue } from './validate';

export type OutputMode = 'standalone' | 'snippet';

export interface GenerateOptions {
  mode: OutputMode;
  /** Emit `% object id` comments and section banners. */
  comments: boolean;
}

export interface GeneratedBlock {
  objectId: string;
  /** 1-based, inclusive line range in the produced document. */
  startLine: number;
  endLine: number;
}

export interface GenerateResult {
  code: string;
  /** Maps every diagram object to the lines it produced (traceability). */
  blocks: GeneratedBlock[];
  issues: ValidationIssue[];
  colorCount: number;
  libraries: string[];
  lineCount: number;
}

const HEADER = [
  '% ---------------------------------------------------------------',
  '% Generated by Flowchart -> TikZ Studio',
  '% Every coordinate below is derived from the editor diagram model.',
  '% Safe to edit by hand, but regenerating will overwrite changes.',
  '% ---------------------------------------------------------------',
];

/**
 * The origin snaps to a coarse grid so that nudging a shape does not shift
 * every coordinate in the document. Keeps regenerated output diff-friendly.
 */
function computeOrigin(d: Diagram) {
  const b = diagramBounds(d);
  const step = Math.max(50, (d.settings.gridSize || 10) * 10);
  const ox = Math.floor((b.x - 20) / step) * step;
  const oy = Math.floor((b.y - 20) / step) * step;
  return { ox, oy };
}

export function generateLatex(
  d: Diagram,
  options: GenerateOptions = { mode: 'standalone', comments: true },
): GenerateResult {
  const colors = new ColorRegistry();
  const libs = new LibraryRegistry();
  const issues: ValidationIssue[] = validateDiagram(d);

  const { ox, oy } = computeOrigin(d);
  const ctx = makeUnitContext(d.settings.unitsPerCm, ox, oy);

  /* ---------------------------------------------------------- body pass */
  // The body is generated first so the preamble knows exactly which colours
  // and libraries are in play. Nothing is emitted "just in case".
  const bodyLines: string[] = [];
  const blockRanges: { objectId: string; start: number; end: number }[] = [];

  const nodeIds = d.order.filter((id) => d.nodes[id]);
  const edgeIds = d.order.filter((id) => d.edges[id]);

  if (options.comments && nodeIds.length) {
    bodyLines.push('% ---- Nodes ----');
  }
  for (const id of nodeIds) {
    const node = d.nodes[id];
    try {
      const res = emitNode(node, ctx, colors, libs);
      const start = bodyLines.length;
      bodyLines.push(...(options.comments ? res.lines : res.lines.filter((l) => !l.trimStart().startsWith('%'))));
      blockRanges.push({ objectId: id, start, end: bodyLines.length - 1 });
      for (const w of res.warnings) {
        issues.push({ severity: 'warning', objectId: id, message: w });
      }
    } catch (err) {
      issues.push({
        severity: 'error',
        objectId: id,
        message: `Could not generate code for ${id}: ${
          err instanceof Error ? err.message : String(err)
        }`,
      });
      bodyLines.push(`% ${id}: generation failed, object skipped`);
    }
  }

  if (options.comments && edgeIds.length) {
    bodyLines.push('% ---- Connectors ----');
  }
  for (const id of edgeIds) {
    const edge = d.edges[id];
    try {
      const res = emitEdge(d, edge, ctx, colors, libs);
      const start = bodyLines.length;
      bodyLines.push(...(options.comments ? res.lines : res.lines.filter((l) => !l.trimStart().startsWith('%'))));
      blockRanges.push({ objectId: id, start, end: bodyLines.length - 1 });
      for (const w of res.warnings) {
        issues.push({ severity: 'warning', objectId: id, message: w });
      }
    } catch (err) {
      issues.push({
        severity: 'error',
        objectId: id,
        message: `Could not generate code for ${id}: ${
          err instanceof Error ? err.message : String(err)
        }`,
      });
      bodyLines.push(`% ${id}: generation failed, object skipped`);
    }
  }

  const needsMath = bodyLines.some((l) => l.includes('$'));

  /* ------------------------------------------------------------ assembly */
  const out: string[] = [];
  const push = (...lines: string[]) => out.push(...lines);

  const colorLines = colors.render();
  const libLines = libs.render();
  const styleLines = baseStyleDefinitions();

  if (options.mode === 'standalone') {
    if (options.comments) push(...HEADER, '');
    push('\\documentclass[border=8pt]{standalone}');
    push('\\usepackage[T1]{fontenc}');
    push('\\usepackage[utf8]{inputenc}');
    if (needsMath) push('\\usepackage{amsmath}');
    push('\\usepackage{xcolor}');
    push('\\usepackage{tikz}');
    if (libLines.length) push(...libLines);
    push('');
    if (colorLines.length) {
      if (options.comments) push('% ---- Colour definitions ----');
      push(...colorLines, '');
    }
    if (options.comments) push('% ---- Style definitions ----');
    push(...styleLines, '');
    push('\\begin{document}');
    push(`\\begin{tikzpicture}[x=1cm, y=1cm]`);
    push(...bodyLines.map((l) => (l.length ? `  ${l}` : l)));
    push('\\end{tikzpicture}');
    push('\\end{document}');
  } else {
    if (options.comments) {
      push(...HEADER);
      push('% Add these to your preamble:');
      push('%   \\usepackage{tikz}');
      push('%   \\usepackage{xcolor}');
      for (const l of libLines) push(`%   ${l}`);
      if (needsMath) push('%   \\usepackage{amsmath}');
      push('');
    }
    if (colorLines.length) {
      if (options.comments) push('% ---- Colour definitions ----');
      push(...colorLines, '');
    }
    if (options.comments) push('% ---- Style definitions ----');
    push(...styleLines, '');
    push('\\begin{tikzpicture}[x=1cm, y=1cm]');
    push(...bodyLines.map((l) => (l.length ? `  ${l}` : l)));
    push('\\end{tikzpicture}');
  }

  // Locate where the body landed so block ranges point at real line numbers.
  const bodyOffset =
    out.length -
    bodyLines.length -
    (options.mode === 'standalone' ? 2 : 1);

  const blocks: GeneratedBlock[] = blockRanges.map((b) => ({
    objectId: b.objectId,
    startLine: bodyOffset + b.start + 1,
    endLine: bodyOffset + b.end + 1,
  }));

  void fmt;
  return {
    code: out.join('\n'),
    blocks,
    issues,
    colorCount: colors.definitions().length,
    libraries: libs.list(),
    lineCount: out.length,
  };
}

/** Convenience wrapper used by tests and exports. */
export function generateStandalone(d: Diagram): string {
  return generateLatex(d, { mode: 'standalone', comments: true }).code;
}
